/* =========================================
   FILE PATHS
========================================= */

function getFilePath(piece, filename) {

    return (
        "./SheetMusic/" +
        encodeURIComponent(piece.folder) +
        "/" +
        encodeURIComponent(filename)
    );

}


/* =========================================
   DISPLAY COLLECTION
========================================= */

function displayMusic(searchTerm = "") {

    musicGrid.innerHTML = "";

    const filteredMusic = sheetMusic.filter(piece => {

        const searchableText = (
            piece.title + " " +
            piece.composer + " " +
            piece.category
        ).toLowerCase();

        return searchableText.includes(searchTerm.toLowerCase());

    });


    collectionCount.textContent =
        `${filteredMusic.length} ${filteredMusic.length === 1 ? "SCORE" : "SCORES"} AVAILABLE`;


    emptyMessage.style.display =
        filteredMusic.length === 0 ? "block" : "none";


    filteredMusic.forEach(piece => {

        const card = document.createElement("article");
        card.className = "music-card";


        const image = document.createElement("div");
        image.className = "card-image";

        const symbol = document.createElement("span");
        symbol.className = "card-symbol";
        symbol.textContent = "♪";

        image.appendChild(symbol);


        const content = document.createElement("div");
        content.className = "card-content";


        const category = document.createElement("div");
        category.className = "card-category";
        category.textContent = piece.category;


        const title = document.createElement("h3");
        title.textContent = piece.title;


        const description = document.createElement("p");
        description.textContent =
            `${piece.composer} · ${piece.pages.length} pages`;


        const link = document.createElement("button");
        link.className = "card-link";
        link.type = "button";
        link.innerHTML = 'View Sheet Music <span>↗</span>';

        link.addEventListener("click", () => {
            openViewer(piece);
        });


        content.appendChild(category);
        content.appendChild(title);
        content.appendChild(description);
        content.appendChild(link);

        card.appendChild(image);
        card.appendChild(content);

        musicGrid.appendChild(card);

    });

}


/* =========================================
   SHEET MUSIC VIEWER
========================================= */

function openViewer(piece) {

    viewerTitle.textContent = piece.title;

    viewerPages.innerHTML = "";

    viewerPageCount.textContent =
        `${piece.pages.length} ${piece.pages.length === 1 ? "PAGE" : "PAGES"}`;


    /* AUDIO PLAYER */

    const oldAudio = document.querySelector(".viewer-audio-container");

    if (oldAudio) {
        oldAudio.remove();
    }


    if (piece.audio) {

        const audioContainer = document.createElement("div");
        audioContainer.className = "viewer-audio-container";


        const audioHeading = document.createElement("div");
        audioHeading.className = "viewer-audio-heading";
        audioHeading.textContent = "LISTEN TO THE PIECE";


        const audioDescription = document.createElement("p");
        audioDescription.className = "viewer-audio-description";
        audioDescription.textContent =
            "Listen while following along with the sheet music.";


        const audio = document.createElement("audio");
        audio.className = "viewer-audio";
        audio.controls = true;
        audio.preload = "metadata";

        audio.src = getFilePath(piece, piece.audio);


        audio.addEventListener("error", () => {

            audioDescription.textContent =
                "Audio could not be loaded. Please check the audio file.";

            audioContainer.classList.add("audio-error");

        });


        audioContainer.appendChild(audioHeading);
        audioContainer.appendChild(audioDescription);
        audioContainer.appendChild(audio);


        viewerPages.parentNode.insertBefore(
            audioContainer,
            viewerPages
        );

    }


    /* SHEET MUSIC PAGES */

    piece.pages.forEach((filename, index) => {

        const pageContainer = document.createElement("div");
        pageContainer.className = "viewer-page";


        const image = document.createElement("img");

        image.src = getFilePath(piece, filename);
        image.alt = `${piece.title} - Page ${index + 1}`;
        image.loading = "lazy";


        image.addEventListener("error", () => {

            pageContainer.innerHTML = "";

            const error = document.createElement("div");
            error.className = "viewer-page-error";

            error.textContent =
                `Page ${index + 1} could not be loaded. Check the folder name and image filename.`;

            pageContainer.appendChild(error);

        });


        pageContainer.appendChild(image);
        viewerPages.appendChild(pageContainer);

    });


    viewerOverlay.classList.add("visible");
    document.body.classList.add("viewer-open");

    viewerOverlay.scrollTop = 0;

}


function closeViewer() {

    viewerOverlay.classList.remove("visible");
    document.body.classList.remove("viewer-open");

    const audio = document.querySelector(".viewer-audio");

    if (audio) {
        audio.pause();
        audio.currentTime = 0;
    }

}


viewerClose.addEventListener("click", closeViewer);


viewerOverlay.addEventListener("click", event => {

    if (event.target === viewerOverlay) {
        closeViewer();
    }

});


document.addEventListener("keydown", event => {

    if (event.key === "Escape") {
        closeViewer();
    }

});


